// Package migrate applies the repository's SQL migrations with goose (as a library). A database that the
// previous home-made, sqlx-compatible migrator already migrated is adopted once ("baselined"): its applied
// versions are copied from _sqlx_migrations into goose_db_version without running anything.
package migrate

import (
	"context"
	"fmt"
	"io/fs"
	"log/slog"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/jackc/pgx/v5/stdlib"
	"github.com/pressly/goose/v3"
	"github.com/pressly/goose/v3/lock"
)

var fileName = regexp.MustCompile(`^(\d+)_(.+)\.sql$`)

// The advisory-lock key the old migrator used. Reusing it makes an old and a new binary starting together
// queue behind each other during the bootstrap.
const lockKey = 7_424_239_913

// Same shape goose itself creates for the postgres dialect.
const createGooseTable = `
create table goose_db_version (
    id integer primary key generated by default as identity,
    version_id bigint not null,
    is_applied boolean not null,
    tstamp timestamp not null default now()
)`

// known returns version -> description (file name with '_' as ' ', as the old migrator recorded it).
func known(files fs.FS) (map[int64]string, error) {
	entries, err := fs.ReadDir(files, ".")
	if err != nil {
		return nil, err
	}
	out := map[int64]string{}
	for _, e := range entries {
		if m := fileName.FindStringSubmatch(e.Name()); m != nil {
			v, err := strconv.ParseInt(m[1], 10, 64)
			if err != nil {
				return nil, err
			}
			if _, dup := out[v]; dup {
				return nil, fmt.Errorf("duplicate migration version %d", v)
			}
			out[v] = strings.ReplaceAll(m[2], "_", " ")
		}
	}
	return out, nil
}

// Run brings the database up to date: one-time baseline if needed, then goose.Up.
func Run(ctx context.Context, pool *pgxpool.Pool, files fs.FS) error {
	if err := baseline(ctx, pool, files); err != nil {
		return fmt.Errorf("baselining from _sqlx_migrations: %w", err)
	}
	db := stdlib.OpenDBFromPool(pool)
	defer db.Close()                               //nolint:errcheck // closing the pool wrapper has nothing to report
	locker, err := lock.NewPostgresSessionLocker() // pg_advisory_lock on a dedicated connection
	if err != nil {
		return err
	}
	p, err := goose.NewProvider(goose.DialectPostgres, db, files, goose.WithSessionLocker(locker))
	if err != nil {
		return err
	}
	results, err := p.Up(ctx)
	for _, r := range results {
		slog.Info("applied migration", "version", r.Source.Version, "file", r.Source.Path, "duration", r.Duration)
	}
	return err
}

func tableExists(ctx context.Context, q interface {
	QueryRow(context.Context, string, ...any) pgx.Row
}, name string) (bool, error) {
	var ok bool
	err := q.QueryRow(ctx, "select to_regclass($1) is not null", name).Scan(&ok)
	return ok, err
}

func versions(ctx context.Context, tx pgx.Tx, query string) (map[int64]bool, error) {
	rows, err := tx.Query(ctx, query)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := map[int64]bool{}
	for rows.Next() {
		var v int64
		if err := rows.Scan(&v); err != nil {
			return nil, err
		}
		out[v] = true
	}
	return out, rows.Err()
}

// baseline is idempotent and safe under concurrent starts (advisory lock + one transaction).
//
//	no _sqlx_migrations rows                    -> nothing to do
//	_sqlx_migrations rows, no goose table       -> create goose table, record every sqlx version as applied
//	both exist                                  -> every sqlx version must already be applied in goose, else error
//
// In every case it refuses: a failed (success=false) sqlx row; a sqlx version this binary has no file for;
// a sqlx description that differs from the file name.
func baseline(ctx context.Context, pool *pgxpool.Pool, files fs.FS) error {
	conn, err := pool.Acquire(ctx)
	if err != nil {
		return err
	}
	defer conn.Release()
	if _, err := conn.Exec(ctx, "select pg_advisory_lock($1)", lockKey); err != nil {
		return err
	}
	defer conn.Exec(context.WithoutCancel(ctx), "select pg_advisory_unlock($1)", lockKey) //nolint:errcheck

	hasSqlx, err := tableExists(ctx, conn, "_sqlx_migrations")
	if err != nil || !hasSqlx {
		return err
	}
	tx, err := conn.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx) //nolint:errcheck

	var failed []int64
	rows, err := tx.Query(ctx, "select version from _sqlx_migrations where not success order by version")
	if err != nil {
		return err
	}
	for rows.Next() {
		var v int64
		if err := rows.Scan(&v); err != nil {
			return err
		}
		failed = append(failed, v)
	}
	rows.Close()
	if len(failed) > 0 {
		return fmt.Errorf("_sqlx_migrations has failed (success=false) rows %v; repair by hand", failed)
	}

	desc := map[int64]string{}
	rows, err = tx.Query(ctx, "select version, description from _sqlx_migrations")
	if err != nil {
		return err
	}
	for rows.Next() {
		var v int64
		var d string
		if err := rows.Scan(&v, &d); err != nil {
			return err
		}
		desc[v] = d
	}
	rows.Close()
	if len(desc) == 0 {
		return nil
	}
	files_, err := known(files)
	if err != nil {
		return err
	}
	var order []int64
	for v, d := range desc {
		fd, ok := files_[v]
		switch {
		case !ok:
			return fmt.Errorf("version %d is applied in _sqlx_migrations but unknown to this binary", v)
		case fd != d:
			return fmt.Errorf("version %d: _sqlx_migrations says %q, this binary's file is %q", v, d, fd)
		}
		order = append(order, v)
	}
	sort.Slice(order, func(i, j int) bool { return order[i] < order[j] })

	hasGoose, err := tableExists(ctx, tx, "goose_db_version")
	if err != nil {
		return err
	}
	if hasGoose {
		applied, err := versions(ctx, tx, "select version_id from goose_db_version where is_applied and version_id > 0")
		if err != nil {
			return err
		}
		for _, v := range order {
			if !applied[v] {
				return fmt.Errorf("goose_db_version disagrees with _sqlx_migrations: version %d is in _sqlx_migrations but not applied in goose_db_version", v)
			}
		}
		return nil
	}

	if _, err := tx.Exec(ctx, createGooseTable); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, "insert into goose_db_version (version_id, is_applied) values (0, true)"); err != nil {
		return err
	}
	for _, v := range order {
		if _, err := tx.Exec(ctx, "insert into goose_db_version (version_id, is_applied) values ($1, true)", v); err != nil {
			return err
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return err
	}
	slog.Info("baselined goose from _sqlx_migrations", "versions", len(order))
	return nil
}
